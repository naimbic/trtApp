// Writes web/src/configs/versions.generated.js: for every release (a commit whose subject ends with "(x.y.z)") the commit hash,
// date, author, size of the change and git tags, for the Versions page. The Docker build has no .git, so the file is committed.
// Run it before committing a release: `node scripts/gen-versions.mjs`. The release being committed gets its hash on the next run
// (until then the page uses the build commit for the running version).
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'

const git = (...args) => execFileSync('git', args, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
const tagsAt = {}
for (const t of git('tag').split('\n').filter(Boolean)) {
    const h = git('rev-list', '-n', '1', t).trim()
    ;(tagsAt[h] ||= []).push(t)
}
const out = {}
let cur = null
for (const line of git('log', '--numstat', '--format=@@%H|%h|%aI|%an|%s').split('\n')) {
    if (line.startsWith('@@')) {
        const [full, short, date, author, ...s] = line.slice(2).split('|')
        const subject = s.join('|')
        const v = subject.match(/\((\d+\.\d+\.\d+)\)\s*$/)?.[1]
        cur = null
        if (!v) continue
        if (out[v]) { out[v].commits += 1; continue } // the newest commit of a version wins
        cur = out[v] = { commit: short, full, date, author, subject: subject.replace(/\s*\(\d+\.\d+\.\d+\)\s*$/, ''), files: 0, added: 0, removed: 0, commits: 1, tags: tagsAt[full] || [] }
    } else if (cur && line.trim()) {
        const [a, r] = line.split('\t')
        cur.files += 1
        cur.added += Number(a) || 0
        cur.removed += Number(r) || 0
    }
}
writeFileSync('web/src/configs/versions.generated.js', `// Generated by scripts/gen-versions.mjs - do not edit.\nexport default ${JSON.stringify(out, null, 4)}\n`)
console.log(`${Object.keys(out).length} releases written`)
