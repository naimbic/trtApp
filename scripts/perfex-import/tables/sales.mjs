import { oid, fk, toDate, toInt, toFloat, toBool, str } from '../lib.mjs'

/** decimal(15,2) string -> Float rounded to 2 decimals ('1234.50' -> 1234.5). */
export const money = (v, dflt = 0) => {
    const n = toFloat(v)
    return n === null ? dflt : Math.round(n * 100) / 100
}
const moneyOrNull = (v) => (v === null || v === undefined || v === '' ? null : money(v))
/** Source created date -> createdAt, only when present (otherwise Prisma default now()). */
const ts = (v) => {
    const d = toDate(v)
    return d ? { createdAt: d } : {}
}

// polymorphic rel_type -> source table (for deterministic id conversion)
const DOC_TABLE = {
    invoice: 'invoices',
    estimate: 'estimates',
    proposal: 'proposals',
    credit_note: 'creditnotes',
    creditnote: 'creditnotes',
    contract: 'contracts',
    expense: 'expenses',
    subscription: 'subscriptions',
    lead: 'leads',
    customer: 'clients',
}
const relFk = (relType, v) => {
    const i = toInt(v)
    if (!i) return null
    return oid(DOC_TABLE[relType] || relType, i)
}

