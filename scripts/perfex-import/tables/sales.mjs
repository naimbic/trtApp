// Tables left as verbatim CrmLegacyRow (purchasing module etc.)
const legacy = (table, pk = 'id') => ({
    model: 'crmLegacyRow',
    id: pk,
    map: (r) => ({
        id: oid(`legacy:${table}`, r[pk]),
        table,
        legacyId: str(r[pk]),
        data: { ...r },
    }),
})

